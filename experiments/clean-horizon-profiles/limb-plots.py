"""Plot verified point rays across the limb, keeping path and prescribed surface separate."""
import json, os, pathlib, sys
destination=pathlib.Path(sys.argv[1]).resolve()
libraries=pathlib.Path(sys.argv[2]).resolve()
assert 'tmp/experiments/clean-horizon-profiles/runs/' in destination.as_posix()
sys.path.insert(0,str(libraries/'python'))
os.environ['MPLCONFIGDIR']=str(destination/'matplotlib-cache')
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
data=json.loads((destination/'combined.json').read_text(encoding='utf-8'))
plt.rcParams.update({'font.size':10,'svg.fonttype':'none','axes.grid':True,'grid.alpha':.2})
def save(fig,name):
    fig.canvas.draw()
    for ext in ['png','svg']:
        target=destination/(name+'.'+ext)
        assert not target.exists()
        fig.savefig(target,dpi=180,bbox_inches='tight',pad_inches=.12)
    plt.close(fig)
for height in [500,2000]:
    rows=sorted([r for r in data['rows'] if r['height']==height],key=lambda r:r['deltaDegrees'])
    y=np.array([r['deltaDegrees'] for r in rows])
    ref=np.array([r['referenceY'] for r in rows]);prod=np.array([r['productionY'] for r in rows]);fine=np.array([r['fineViewY'] for r in rows]);hw=np.array([r['referenceYHalfWidth95'] for r in rows])
    total=np.array([r['productionTotalYProxy'] for r in rows]);hybrid=np.array([r['referenceTotalYProxy'] for r in rows])
    luma=lambda v:.2126*v[0]+.7152*v[1]+.0722*v[2]
    surface=np.array([luma(r['productionSurfaceRgb']) for r in rows]);refsurface=np.array([luma(r['referenceSurfaceRgb']) for r in rows])
    pixels=[r for r in rows if r.get('stockRgb') is not None]
    fig,axes=plt.subplots(1,4,figsize=(17,10),sharey=True,gridspec_kw={'width_ratios':[3.5,2.4,3.5,1.8]},layout='constrained')
    axes[0].fill_betweenx(y,ref-hw,ref+hw,color='black',alpha=.15,label='Reference pointwise95%')
    axes[0].plot(ref,y,'k-',label='MYSTIC black boundary')
    axes[0].plot(prod,y,color='#0077ba',label='Production N4 / sphere')
    axes[0].plot(fine,y,'--',color='#c35a10',label='Same N4 /480intervals')
    axes[0].set_xlabel('Atmospheric luminance (cd m$^{-2}$)')
    axes[0].set_ylabel('Degrees above geometric limb (ground is below0)')
    axes[0].legend(fontsize=8,loc='best')
    axes[1].plot(surface,y,color='#0077ba',label='Production attenuation')
    axes[1].plot(refsurface,y,'k--',label='Independent layer transmission')
    axes[1].set_xlabel('Surface contribution\nLinear-RGB luminance proxy')
    axes[1].legend(fontsize=8)
    axes[2].plot(total,y,color='#0077ba',label='Production sphere composite')
    axes[2].plot(hybrid,y,'k-',label='MYSTIC path + common surface')
    axes[2].scatter([r['stockTotalYProxy'] for r in pixels],[r['deltaDegrees'] for r in pixels],s=12,facecolors='none',edgecolors='#c35a10',label='Stock4Kpixel centers')
    axes[2].set_xlabel('Path + surface\nLinear-RGB luminance proxy')
    axes[2].legend(fontsize=8)
    edges=np.r_[y[0]-(y[1]-y[0])/2,(y[:-1]+y[1:])/2,y[-1]+(y[-1]-y[-2])/2]
    colors=np.array([[r['productionDisplayRgb'],r['referenceDisplayRgb']] for r in rows])/255
    axes[3].pcolormesh([0,1,2],edges,colors,shading='flat',rasterized=True)
    axes[3].set_xticks([.5,1.5],['Production','Reference hybrid'],rotation=45)
    axes[3].set_xlabel('Common exposure\nSampled angular cells')
    axes[3].grid(False)
    for ax in axes: ax.axhline(0,color='#a32e2e',linewidth=.9)
    axes[0].set_ylim(-.56,2.03)
    fig.suptitle(f'San Jose noon, {height:,} m: continuous sky trace and opaque-ground transition\nSame ARM atmosphere; black-boundary transport, then a common prescribedRGBsurface')
    save(fig,f'limb-trace-{height}')
    fig,axes=plt.subplots(3,1,figsize=(14,10),sharex=True,layout='constrained')
    axes[0].fill_between(y,ref-hw,ref+hw,color='black',alpha=.15)
    axes[0].plot(y,ref,'k.-',label='MYSTIC atmospheric path ±95%')
    axes[0].plot(y,prod,'.-',color='#0077ba',label='Production atmospheric path')
    axes[0].set_ylabel('Path luminance (cd m$^{-2}$)');axes[0].legend(fontsize=9)
    axes[1].plot(y,hybrid,'k.-',label='Reference path + common surface')
    axes[1].plot(y,total,'.-',color='#0077ba',label='Production sphere composite')
    axes[1].scatter([r['deltaDegrees'] for r in pixels],[r['stockTotalYProxy'] for r in pixels],s=45,facecolors='none',edgecolors='#c35a10',label='Stock4Kpixels')
    axes[1].set_ylabel('Total linear-RGB\nluminance proxy');axes[1].legend(fontsize=9)
    for channel,c in enumerate(['#bd2828','#168139','#2364bb']):
        axes[2].plot(y,[r['productionDisplayRgb'][channel] for r in rows],color=c,label='Production '+'RGB'[channel])
        axes[2].plot(y,[r['referenceDisplayRgb'][channel] for r in rows],'--',color=c,label='Reference '+'RGB'[channel])
    axes[2].set_ylabel('Common-exposure PNG channel (0–255)')
    axes[2].set_xlabel('Degrees above geometric limb: opaque ground below0, sky above0')
    axes[2].legend(fontsize=8,ncol=3)
    for ax in axes: ax.axvline(0,color='#a32e2e',linewidth=.9)
    axes[2].set_xlim(-.025,.025)
    fig.suptitle(f'Fine straddling trace — {height:,} m\nPoint rays, including paired samples near ±0.00025°; no pixel-footprint averaging')
    save(fig,f'limb-edge-{height}')
    fig,axes=plt.subplots(2,1,figsize=(14,8),sharex=True,layout='constrained')
    axes[0].fill_between(y,ref-hw,ref+hw,color='black',alpha=.15)
    axes[0].plot(y,ref,'k-',label='MYSTIC atmospheric path')
    axes[0].plot(y,prod,color='#0077ba',label='Production N4 path')
    axes[0].set_ylabel('Path luminance (cd m$^{-2}$)');axes[0].legend()
    axes[1].plot(y,hybrid,'k-',label='Reference path + commonRGBsurface')
    axes[1].plot(y,total,color='#0077ba',label='Production sphere composite')
    axes[1].set_ylabel('Total linear-RGB luminance proxy');axes[1].legend()
    axes[1].set_xlabel('Degrees above limb: fine near0; sparse controls below−0.55° and above2°')
    for ax in axes: ax.axvline(0,color='#a32e2e',linewidth=.9)
    axes[1].set_xlim(-2.05,5.05)
    fig.suptitle(f'Combined old sky data and new ground trace — {height:,} m')
    save(fig,f'limb-context-{height}')
(destination/'plot-runtime.json').write_text(json.dumps({'matplotlib':matplotlib.__version__,'numpy':np.__version__,'python':sys.version}),encoding='utf-8')
